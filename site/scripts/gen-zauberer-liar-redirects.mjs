// Writes the zauberer-liar.de block of public/_redirects from ops/redirects-zauberer-liar.csv
// (the old domain is a domain alias of this Netlify project since 2026-10-07).
//   node scripts/gen-zauberer-liar-redirects.mjs
// The block sits between the BEGIN/END markers and is replaced on every run.
import { readFileSync, writeFileSync } from 'node:fs';

const MAIN = 'https://liar-entertainer.com';
const HOSTS = ['https://zauberer-liar.de', 'https://www.zauberer-liar.de', 'http://zauberer-liar.de', 'http://www.zauberer-liar.de'];
const BEGIN = '# >>> zauberer-liar.de (generated by scripts/gen-zauberer-liar-redirects.mjs — do not edit by hand)';
const END = '# <<< zauberer-liar.de';

const rows = readFileSync('../ops/redirects-zauberer-liar.csv', 'utf8')
  .split(/\r?\n/).slice(1).filter(Boolean).map((l) => l.split(','));
const pad = (s, n) => (s.length >= n ? s + ' ' : s.padEnd(n));

const lines = [BEGIN];
for (const host of HOSTS) {
  for (const [from, to] of rows) {
    lines.push(`${pad(host + from, 70)}${pad(MAIN + to, 70)}301!`);
    // city pages were also reachable without ".html"
    const city = from.match(/^\/(zauberer-[a-z-]+)\.html$/);
    if (city) lines.push(`${pad(`${host}/${city[1]}`, 70)}${pad(MAIN + to, 70)}301!`);
  }
  lines.push(`${pad(host + '/*', 70)}${pad(MAIN + '/zauberer/', 70)}301!`);
}
lines.push(END);

const file = 'public/_redirects';
let s = readFileSync(file, 'utf8');
const nl = s.includes('\r\n') ? '\r\n' : '\n';
s = s.replace(/\r\n/g, '\n');
const block = lines.join('\n');
if (s.includes(BEGIN)) s = s.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), block);
else {
  // right after the host rules (www / netlify.app), before any path rule of the main site
  const anchor = 'http://liar-entertainer-relaunch.netlify.app/*';
  const i = s.indexOf('\n', s.indexOf(anchor));
  if (s.indexOf(anchor) < 0) throw new Error('anchor not found');
  s = s.slice(0, i + 1) + '\n' + block + '\n' + s.slice(i + 1);
}
writeFileSync(file, s.replace(/\n/g, nl));
console.log(`[zauberer-liar] ${lines.length - 2} rules`);
